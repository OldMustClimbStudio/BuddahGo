using BuddahGo.AI;
using BuddahGo.Match;
using BuddahGo.Tests;
using NUnit.Framework;
using UnityEngine;

public class AIDifficultyProfilesTests
{
    [Test]
    public void TierProfilesLoadAndValidate()
    {
        EveryCase.Parts(
            ("every tier loads a valid thrust vector profile", () =>
                EveryCase.Check(new[] { SoloDifficulty.Easy, SoloDifficulty.Normal, SoloDifficulty.Hard }, tier =>
                {
                    var profile = AIDifficultyProfiles.Load(tier);
                    Assert.That(profile, Is.Not.Null, "Resources/AI/" + tier + ".asset is generated by AIDifficultyAssetTool.Build");
                    Assert.That(profile.UseWallCorridor, Is.True);
                    Assert.DoesNotThrow(profile.ValidateConfiguration);
                }, tier => "tier=" + tier)),
            ("a profile rejects non-finite and out-of-range values", () =>
            {
                var profile = ScriptableObject.CreateInstance<AIDifficultyProfile>();
                try
                {
                    profile.ValidateConfiguration();
                    profile.TargetSpeed = float.NaN;
                    Assert.Throws<System.ArgumentException>(() => profile.ValidateConfiguration());
                    profile.TargetSpeed = 80f; profile.RolloutSampleTicks = 0;
                    Assert.Throws<System.ArgumentException>(() => profile.ValidateConfiguration());
                }
                finally { Object.DestroyImmediate(profile); }
            }));
    }

    [Test] public void ResolveGivesEachRacerItsOwnInstanceWithLineVariety()
    {
        var a = AIDifficultyProfiles.Resolve(SoloDifficulty.Normal, 0); var b = AIDifficultyProfiles.Resolve(SoloDifficulty.Normal, 1);
        try
        {
            Assert.That(a, Is.Not.SameAs(b)); Assert.That(a, Is.Not.SameAs(AIDifficultyProfiles.Load(SoloDifficulty.Normal)));
            Assert.That(a.LateralOffset, Is.Not.EqualTo(b.LateralOffset));
        }
        finally { Object.DestroyImmediate(a); Object.DestroyImmediate(b); }
    }
}
