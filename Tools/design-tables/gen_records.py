"""Generate C# record classes and ProjectConfigDatabase lists from the design-table CSV mirrors.

Usage: python Tools/design-tables/gen_records.py <repo_root>
Reads Assets/Design/Tables/_Export/<Workbook>/<Sheet>.csv header rows for the in-scope sheets listed in
Assets/Design/Tables/scope.json and writes:
  Assets/Scripts/Config/Definitions/ProjectConfigRecords.Generated.cs
  Assets/Scripts/Config/Definitions/ProjectConfigDatabase.Generated.cs
Existing hand-written records (SkillDefinitionRecord, SkillBalanceRecord, SkillEffectParamRecord,
SkillSelectionRuleRecord, DefaultLoadoutRecord, GlobalRuleRecord) are left untouched.
"""
import csv, json, os, sys

ROOT = sys.argv[1]
TABLES = os.path.join(ROOT, 'Assets', 'Design', 'Tables')
scope = json.load(open(os.path.join(TABLES, 'scope.json'), encoding='utf-8'))
HAND_WRITTEN = set(scope['handWrittenRecords'])
RECORD_NAME_OVERRIDE = scope.get('recordNameOverride', {})
LIST_NAME_OVERRIDE = scope.get('listNameOverride', {})

def cs_type(type_expr):
    base = type_expr.split('#')[0]
    if base.startswith('list,'):
        elem = base[5:]
        if elem.startswith('enum:') or elem in ('string', 'text'):
            return 'List<string>', 'new List<string>()'
        if elem == 'float':
            return 'List<float>', 'new List<float>()'
        if elem == 'int':
            return 'List<int>', 'new List<int>()'
        return 'List<string>', 'new List<string>()'
    if base.startswith('enum:'):
        return 'string', 'string.Empty'
    return {'int': ('int', '0'), 'float': ('float', '0f'), 'bool': ('bool', 'false'), 'string': ('string', 'string.Empty'), 'text': ('string', 'string.Empty'),
            'vector3': ('Vector3', 'Vector3.zero'), 'vector2': ('Vector2', 'Vector2.zero'), 'color': ('Color', 'Color.white'), 'curve': ('AnimationCurve', 'new AnimationCurve()')}[base]

def record_name(sheet):
    return RECORD_NAME_OVERRIDE.get(sheet, sheet + 'Record')

def list_name(sheet):
    if sheet in LIST_NAME_OVERRIDE:
        return LIST_NAME_OVERRIDE[sheet]
    camel = sheet[0].lower() + sheet[1:]
    if camel.endswith('y') and camel[-2] not in 'aeiou':
        return camel[:-1] + 'ies'
    return camel + ('es' if camel.endswith(('s', 'sh', 'ch', 'x')) else 's')

records = []
lists = []
for wb, sheets in scope['export'].items():
    for sheet in sheets:
        path = os.path.join(TABLES, '_Export', wb, sheet + '.csv')
        with open(path, encoding='utf-8', newline='') as f:
            rows = list(csv.reader(f))
        var, typ, grp, com = rows[0][1:], rows[1][1:], rows[2][1:], rows[3][1:]
        rec = record_name(sheet)
        if rec not in HAND_WRITTEN:
            fields = []
            for v, t, g, c in zip(var, typ, grp, com):
                if g == 'doc' or not v or v.startswith('#'):
                    continue
                ct, default = cs_type(t)
                key = '#key' in t
                fields.append((v, ct, default, c.replace('"', '\\"'), key, t))
            records.append((rec, wb, sheet, fields))
        lists.append((wb, sheet, rec, list_name(sheet)))

out = ['// <auto-generated> by Tools/design-tables/gen_records.py from Assets/Design/Tables/_Export headers. Do not edit by hand.',
       '// Field names equal the ##var row of the sheet; enum columns are stored as strings and validated on import.',
       'using System;', 'using System.Collections.Generic;', 'using UnityEngine;', '']
for rec, wb, sheet, fields in records:
    out.append(f'/// <summary>{wb}.xlsx / {sheet}</summary>')
    out.append('[Serializable]')
    out.append(f'public class {rec}')
    out.append('{')
    for v, ct, default, c, key, t in fields:
        tip = f' [Tooltip("{c}")]' if c else ''
        out.append(f'    /// <summary>{t}{" (key)" if key else ""}</summary>')
        out.append(f'   {tip} public {ct} {v} = {default};'.replace('    public', '    public') if tip else f'    public {ct} {v} = {default};')
    out.append('}')
    out.append('')
open(os.path.join(ROOT, 'Assets', 'Scripts', 'Config', 'Definitions', 'ProjectConfigRecords.Generated.cs'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))

out = ['// <auto-generated> by Tools/design-tables/gen_records.py. Do not edit by hand.',
       '// One list per exported design-table sheet. Hand-written lists for the original six records stay in ProjectConfigDatabase.cs.',
       'using System.Collections.Generic;', 'using UnityEngine;', '',
       'public partial class ProjectConfigDatabase', '{']
for wb, sheet, rec, ln in lists:
    if rec in HAND_WRITTEN:
        continue
    out.append(f'    [Header("{wb} / {sheet}")]')
    out.append(f'    public List<{rec}> {ln} = new List<{rec}>();')
out.append('}')
out.append('')
open(os.path.join(ROOT, 'Assets', 'Scripts', 'Config', 'Definitions', 'ProjectConfigDatabase.Generated.cs'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))

# sheet -> (record, list) map consumed by the exporter
mp = {f'{wb}/{sheet}': {'record': rec, 'list': ln} for wb, sheet, rec, ln in lists}
json.dump(mp, open(os.path.join(TABLES, 'export-map.json'), 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
print('records', len(records), 'lists', len(lists))
